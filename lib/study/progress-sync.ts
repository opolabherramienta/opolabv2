import type { SupabaseClient } from "@supabase/supabase-js";
import { getSessionKind, madridDateKey, toDateKey } from "./sessions";

type LinkedSession = {
  taskType: string | null;
  title: string | null;
  userTopicId?: string | null;
  userPracticalId?: string | null;
};

type DeletedSession = LinkedSession & { id: string; status: string | null };

/**
 * True when deleting `session` must take back the progress it gave: it was
 * completed and linked to a topic or practical. A study session only takes
 * "studied" back when no other completed study session of the topic is left.
 */
export function revertsProgressOnDelete(session: DeletedSession, all: DeletedSession[]) {
  if (session.status !== "completed") return false;

  const kind = getSessionKind(session.taskType, session.title);

  if (kind === "rest") return false;
  if (kind === "practical") return Boolean(session.userPracticalId);
  if (!session.userTopicId) return false;
  if (kind !== "study") return true;

  return !all.some(
    (other) =>
      other.id !== session.id &&
      other.status === "completed" &&
      other.userTopicId === session.userTopicId &&
      getSessionKind(other.taskType, other.title) === "study",
  );
}

/** Description of the session written when a topic is marked in Temas. */
export const STUDIED_IN_TOPICS_NOTE = "Marcado como estudiado en Temas.";

export type TopicSession = {
  id: string;
  title: string | null;
  description: string | null;
  taskType: string | null;
  taskDate: string | null;
  status: string | null;
  completedAt: string | null;
  isAutoGenerated: boolean;
};

export type StudiedChange =
  | { action: "none" }
  | { action: "create" }
  | { action: "complete" | "reopen" | "delete"; id: string };

/**
 * What marking a topic as studied (or not) in Temas does to its calendar
 * sessions, so the calendar, the XP and the plan tell the same story:
 * - studied: the planned study session is completed today; without one, a
 *   completed session is written. A topic already completed stays as it is.
 * - not studied: the last completed study session goes back to pending when
 *   the plan wrote it, and is removed when Temas wrote it. A session the user
 *   wrote by hand is left alone.
 */
export function studiedSessionChange(sessions: TopicSession[], studied: boolean): StudiedChange {
  const study = sessions.filter(
    (session) =>
      session.status !== "cancelled" &&
      getSessionKind(session.taskType, session.title) === "study",
  );
  const completed = study
    .filter((session) => session.status === "completed")
    .sort((a, b) =>
      (a.completedAt ?? a.taskDate ?? "").localeCompare(b.completedAt ?? b.taskDate ?? ""),
    );

  if (studied) {
    if (completed.length > 0) return { action: "none" };

    const pending = study
      .filter((session) => session.status === "pending")
      .sort((a, b) => (a.taskDate ?? "").localeCompare(b.taskDate ?? ""));

    return pending.length > 0 ? { action: "complete", id: pending[0].id } : { action: "create" };
  }

  const last = completed[completed.length - 1];

  if (!last) return { action: "none" };
  if (last.isAutoGenerated) return { action: "reopen", id: last.id };

  return last.description === STUDIED_IN_TOPICS_NOTE
    ? { action: "delete", id: last.id }
    : { action: "none" };
}

type StudiedTopic = {
  userTopicId: string;
  baseTopicId: string;
  number: number | null;
  title: string;
};

// Applies studiedSessionChange. Throws when the calendar could not be
// updated; the topic itself is already stored by then.
export async function syncTopicStudied(
  supabase: SupabaseClient,
  userId: string,
  topic: StudiedTopic,
  studied: boolean,
): Promise<StudiedChange["action"]> {
  const current = await supabase
    .from("calendar_tasks")
    .select("id, title, description, task_type, task_date, status, completed_at, is_auto_generated")
    .eq("user_id", userId)
    .eq("user_topic_id", topic.userTopicId);

  if (current.error) {
    throw new Error(current.error.message);
  }

  const change = studiedSessionChange(
    (
      (current.data ?? []) as Array<{
        id: string;
        title: string | null;
        description: string | null;
        task_type: string | null;
        task_date: string | null;
        status: string | null;
        completed_at: string | null;
        is_auto_generated: boolean | null;
      }>
    ).map((row) => ({
      id: row.id,
      title: row.title,
      description: row.description,
      taskType: row.task_type,
      taskDate: row.task_date,
      status: row.status,
      completedAt: row.completed_at,
      isAutoGenerated: row.is_auto_generated === true,
    })),
    studied,
  );
  const todayKey = madridDateKey();
  const table = supabase.from("calendar_tasks");
  let result: { error: { message: string } | null } = { error: null };

  if (change.action === "complete") {
    // Brought to today: that is when it was studied.
    result = await table
      .update({ status: "completed", completed_at: new Date().toISOString(), task_date: todayKey })
      .eq("id", change.id)
      .eq("user_id", userId);
  } else if (change.action === "reopen") {
    result = await table
      .update({ status: "pending", completed_at: null })
      .eq("id", change.id)
      .eq("user_id", userId);
  } else if (change.action === "delete") {
    result = await table.delete().eq("id", change.id).eq("user_id", userId);
  } else if (change.action === "create") {
    const title = topic.number === null ? topic.title : `Tema ${topic.number}: ${topic.title}`;

    result = await table.insert({
      user_id: userId,
      title: title.length <= 90 ? title : `${title.slice(0, 89).trimEnd()}…`,
      description: STUDIED_IN_TOPICS_NOTE,
      task_date: todayKey,
      task_type: "study_topic",
      status: "completed",
      completed_at: new Date().toISOString(),
      base_topic_id: topic.baseTopicId,
      user_topic_id: topic.userTopicId,
      is_auto_generated: false,
    });
  }

  if (result.error) {
    throw new Error(result.error.message);
  }

  return change.action;
}

// Completing a planned session also moves its topic or practical forward, and
// undoing it moves it back. Throws when the progress could not be saved; the
// session itself is already stored by then.
export async function syncSessionProgress(
  supabase: SupabaseClient,
  userId: string,
  session: LinkedSession,
  direction: 1 | -1,
) {
  const kind = getSessionKind(session.taskType, session.title);
  const todayKey = toDateKey(new Date());

  if (session.userTopicId && kind !== "practical" && kind !== "rest") {
    const current = await supabase
      .from("user_topics")
      .select("review_count, simulation_count")
      .eq("id", session.userTopicId)
      .eq("user_id", userId)
      .maybeSingle();

    if (current.error || !current.data) {
      throw new Error(current.error?.message ?? "Tema no encontrado");
    }

    const row = current.data as {
      review_count: number | null;
      simulation_count: number | null;
    };
    const patch: Record<string, unknown> =
      kind === "study"
        ? { studied_done: direction > 0 }
        : kind === "review"
          ? {
              review_count: Math.max(0, (row.review_count ?? 0) + direction),
              ...(direction > 0 ? { last_review_date: todayKey } : {}),
            }
          : {
              simulation_count: Math.max(0, (row.simulation_count ?? 0) + direction),
            };
    const result = await supabase
      .from("user_topics")
      .update(patch)
      .eq("id", session.userTopicId)
      .eq("user_id", userId);

    if (result.error) {
      throw new Error(result.error.message);
    }
  }

  if (session.userPracticalId && kind === "practical") {
    const current = await supabase
      .from("user_practicals")
      .select("times_worked, status")
      .eq("id", session.userPracticalId)
      .eq("user_id", userId)
      .maybeSingle();

    if (current.error || !current.data) {
      throw new Error(current.error?.message ?? "Práctico no encontrado");
    }

    const row = current.data as {
      times_worked: number | null;
      status: string | null;
    };
    const result = await supabase
      .from("user_practicals")
      .update({
        times_worked: Math.max(0, (row.times_worked ?? 0) + direction),
        ...(direction > 0 && row.status === "not_started" ? { status: "worked" } : {}),
        ...(direction > 0 ? { last_worked_date: todayKey } : {}),
      })
      .eq("id", session.userPracticalId)
      .eq("user_id", userId);

    if (result.error) {
      throw new Error(result.error.message);
    }
  }
}
